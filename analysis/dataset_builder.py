"""
dataset_builder.py

Reads analysis/config.yaml, then for every non-overlapping weekly window between
study_date_start and study_date_end:
  1. Writes  analysis/dataset_definition_week_N.py  with the dates baked in.
  2. Rewrites project.yaml to contain:
       - An action to run this builder script itself.
       - One ehrql generate-dataset action per weekly definition file.
       - The final concatenation action (analysis/analysis.py).

Run locally before committing:
    python analysis/dataset_builder.py
"""

from __future__ import annotations

import gzip
from datetime import date, timedelta
from pathlib import Path

import yaml

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
REPO_ROOT = Path(__file__).parent.parent
CONFIG_PATH = REPO_ROOT / "analysis" / "config.yaml"
PROJECT_YAML_PATH = REPO_ROOT / "project.yaml"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def iter_weeks(start: date, end: date):
    """Yield (week_num, period_start, period_end) for each non-overlapping week."""
    current = start
    week_num = 1
    while current <= end:
        period_end = min(current + timedelta(days=6), end)
        yield week_num, current, period_end
        current = period_end + timedelta(days=1)
        week_num += 1


def make_definition_content(
    week_num: int,
    start_date: str,
    end_date: str,
    dummy_population_size: int,
    codelist_path: str,
) -> str:
    """Return the full source of a weekly dataset definition file."""
    return f"""\
# Auto-generated by analysis/dataset_builder.py — do not edit by hand.
# Week {week_num}: {start_date} to {end_date}
from ehrql import case, codelist_from_csv, create_dataset
from ehrql.tables.core import patients
from ehrql.tables.tpp import emergency_care_attendances, addresses, when, ethnicity_from_sus

study_date_start = "{start_date}"
study_date_end = "{end_date}"

dataset = create_dataset()
dataset.configure_dummy_data(population_size={dummy_population_size})

# Codelists
cvd_codes = codelist_from_csv("{codelist_path}", column="code")

# Population filters
is_female_or_male = patients.sex.is_in(["female", "male"])

age_at_start = patients.age_on(study_date_start)
age_filter = (age_at_start >= 0) & (age_at_start <= 110)

all_attendances = emergency_care_attendances.where(
    emergency_care_attendances.arrival_date.is_on_or_between(study_date_start, study_date_end)
)
has_diagnosis = (
    all_attendances.where(all_attendances.diagnosis_01.is_not_null()).exists_for_patient()
)

# Deprivation quintile
imd_rounded = addresses.for_patient_on(study_date_start).imd_rounded
max_imd = 32844
imd_quintile = case(
    when((imd_rounded >= 0) & (imd_rounded <= int(max_imd * 1 / 5))).then(1),
    when(imd_rounded <= int(max_imd * 2 / 5)).then(2),
    when(imd_rounded <= int(max_imd * 3 / 5)).then(3),
    when(imd_rounded <= int(max_imd * 4 / 5)).then(4),
    when(imd_rounded <= max_imd).then(5),
    otherwise=99,
)

dataset.define_population(age_filter & is_female_or_male & has_diagnosis)

# Columns
dataset.age_at_start = age_at_start
dataset.imd_quintile = imd_quintile
dataset.ethnicity_group = ethnicity_from_sus.code.map_values(
    {{
        "A": "White",  "B": "White",  "C": "White",
        "D": "Mixed",  "E": "Mixed",  "F": "Mixed",  "G": "Mixed",
        "H": "Asian",  "J": "Asian",  "K": "Asian",  "L": "Asian",
        "M": "Black",  "N": "Black",  "P": "Black",
        "R": "Other",  "S": "Other",
        "Z": "Not stated",
    }},
    default="Unknown",
)
dataset.primary_diag = (
    all_attendances
    .sort_by(all_attendances.arrival_date)
    .first_for_patient()
    .diagnosis_01
)
dataset.attendance_date = (
    all_attendances
    .sort_by(all_attendances.arrival_date)
    .first_for_patient()
    .arrival_date
)
"""


def make_project_yaml(weeks: list[tuple[int, date, date]]) -> str:
    """Return the full text of project.yaml for the given list of weekly windows."""
    lines: list[str] = [
        "version: '5.0'",
        "",
        "actions:",
        "",
        "  # Step 1 — generate all per-week definition files and rewrite this YAML.",
        "  run_dataset_builder:",
        "    run: python:v2 analysis/dataset_builder.py",
        "    outputs:",
        "      moderately_sensitive:",
        "        dataset: analysis/composite/dummyset.csv.gz",
        "",
    ]

    for week_num, _start, _end in weeks:
        defn_path = f"analysis/composite/dataset_definition_week_{week_num}.py"
        out_path = f"output/composite/output_dataset_week_{week_num}.csv.gz"
        lines += [
            f"  # Week {week_num}: {_start.isoformat()} to {_end.isoformat()}",
            f"  generate_dataset_week_{week_num}:",
            f"    run: ehrql:v1 generate-dataset {defn_path} --output {out_path}",
            f"    needs: [run_dataset_builder]",
            f"    outputs:",
            f"      highly_sensitive:",
            f"        dataset: {out_path}",
            "",
        ]

    # analysis action — needs every weekly action
    needs_lines = "\n".join(
        f"      - generate_dataset_week_{n}" for n, _, _ in weeks
    )
    lines += [
        "  # Final step — concatenate all weekly outputs.",
        "  analysis:",
        "    run: python:v2 analysis/analysis.py",
        "    needs:",
        needs_lines,
        "    outputs:",
        "      highly_sensitive:",
        "        analysis: output/analysis_results.csv.gz",
        "",
    ]

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main() -> None:
    with open(CONFIG_PATH) as f:
        cfg = yaml.safe_load(f)

    study_start = date.fromisoformat(cfg["study_date_start"])
    study_end = date.fromisoformat(cfg["study_date_end"])
    codelist_path: str = cfg["codelist_path"]
    dummy_pop: int = cfg["dummy_population_size"]
    definitions_dir = REPO_ROOT / cfg["definitions_dir"] / "composite"
    output_composite_dir = REPO_ROOT / cfg["output_composite_dir"]
    builder_output_path = definitions_dir / "dummyset.csv.gz"

    definitions_dir.mkdir(parents=True, exist_ok=True)
    output_composite_dir.mkdir(parents=True, exist_ok=True)
    with gzip.open(builder_output_path, "wt"):
        pass

    weeks = list(iter_weeks(study_start, study_end))
    print(f"Study period: {study_start} to {study_end} → {len(weeks)} weeks")

    # 1. Write per-week definition files
    for week_num, period_start, period_end in weeks:
        defn_path = definitions_dir / f"dataset_definition_week_{week_num}.py"
        content = make_definition_content(
            week_num=week_num,
            start_date=period_start.isoformat(),
            end_date=period_end.isoformat(),
            dummy_population_size=dummy_pop,
            codelist_path=codelist_path,
        )
        defn_path.write_text(content)
        print(f"  Written {defn_path.name}")

    # 2. Rewrite project.yaml
    project_yaml_content = make_project_yaml(weeks)
    PROJECT_YAML_PATH.write_text(project_yaml_content)
    print(f"\nRewritten {PROJECT_YAML_PATH} with {len(weeks)} weekly actions.")


if __name__ == "__main__":
    main()
